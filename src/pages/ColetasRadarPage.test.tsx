import { act, render, screen, waitFor } from "@testing-library/react";
import { beforeEach, expect, it, vi } from "vitest";
const mocks = vi.hoisted(() => ({ read: vi.fn(), callback: undefined as undefined | (() => void), stop: vi.fn() }));
vi.mock("@tanstack/react-router", () => ({ useNavigate: () => vi.fn() }));
vi.mock("@/components/BwaNav", () => ({ default: () => null }));
vi.mock("@/components/BwaFooter", () => ({ default: () => null }));
vi.mock("@/lib/useSeo", () => ({ useSeo: () => undefined }));
vi.mock("@/hooks/useNeighborhoodInterest", () => ({ useNeighborhoodInterest: () => undefined }));
vi.mock("@/lib/assistant/radarColetas.functions", () => ({ getRadarColetas: mocks.read }));
vi.mock("@/lib/assistant/radarRealtime", () => ({ subscribeRadarCollections: (callback: () => void) => { mocks.callback = callback; return mocks.stop; } }));
import ColetasRadarPage from "./ColetasRadarPage";
beforeEach(() => { mocks.read.mockReset(); mocks.stop.mockClear(); });
it("atualiza o histórico público pelo aviso e conserva estados vindos do Radar", async () => {
  const observation = { coletado_em: "2026-10-13", periodo_inicio: "2026-01-01", periodo_fim: "2026-09-30", fonte_nome: "GuestFavorites", amostra_n: 2424, ativo: true };
  const initial = { bairros: ["Pinheiros"], bairro: "Pinheiros", coletas: [observation] };
  mocks.read.mockResolvedValue({ ...initial, coletas: [{ ...observation, coletado_em: "2026-10-17" }, { ...observation, ativo: false }] });
  const view = render(<ColetasRadarPage data={initial} />);
  act(() => mocks.callback?.());
  await waitFor(() => expect(mocks.read).toHaveBeenCalledWith({ data: { bairro: "Pinheiros" } }));
  expect(await screen.findByText(/17\/10\/2026/)).toHaveTextContent("Status: ativa");
  expect(screen.getByText(/13\/10\/2026/)).toHaveTextContent("Status: substituída");
  mocks.read.mockRejectedValue(new Error("offline"));
  act(() => mocks.callback?.());
  await screen.findByRole("alert");
  mocks.read.mockResolvedValue(initial);
  act(() => mocks.callback?.());
  await waitFor(() => expect(screen.queryByRole("alert")).toBeNull());
  view.unmount();
  expect(mocks.stop).toHaveBeenCalledTimes(1);
});